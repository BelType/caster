/**
 * `scripts/rebuild-harfbuzz.js` — rebuilds `vendor/harfbuzz.js` and `vendor/harfbuzz.wasm`: harfbuzzjs 1.6.1 compiled with HarfBuzz's fallback shaping left in (DESIGN.md S101).
 *
 * @remarks
 * harfbuzzjs builds with `-DHB_TINY`, which implies `HB_NO_LEGACY`, which switches off `HB_NO_OT_SHAPE_FALLBACK` (the Hebrew, Arabic and Thai fallback shapers), `HB_NO_FALLBACK_SHAPE` and `HB_NO_OT_KERN`. A face that leaves its combining marks out of the GDEF glyph classes (Arial Unicode's Hebrew points) then keeps each mark's advance, where Blink's HarfBuzz zeroes it and places the mark by its fallback. The one change here is the last line of harfbuzzjs's `config-override.h`, `#undef HB_NO_LEGACY`; `HB_CONFIG_OVERRIDE_H` is included after `HB_NO_LEGACY` is defined and before it expands (hb-config.hh).
 *
 * The compiler is Emscripten in a container, pinned by digest, so the build is the same on any machine with Docker. Nothing is installed; the image is removed with `docker rmi` afterwards.
 *
 *     node scripts/rebuild-harfbuzz.js <harfbuzzjs-1.6.1 checkout, no .git> <harfbuzz checkout at HB_COMMIT>
 *
 * The bundling is what `scripts/bundle-vendor.js` does to every Emscripten glue (esbuild, same options and stub), run on the new glue with harfbuzzjs's own `dist/index.mjs` from `node_modules`. Run on the unchanged sources with the 4.0.13 image, the same road wrote this directory's earlier `harfbuzz.wasm` and `harfbuzz.js` bit for bit.
 *
 * @packageDocumentation
 */

import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

/** What the build was made with; `vendor/README.md` repeats it. */
export const BUILD = {
  image: 'emscripten/emsdk:6.0.13',
  digest: 'sha256:fb7864e398acfda863dfcea78b8bc8adad359fa60c6a0bbeb845931de64aa68a',
  harfbuzzjs: '1.6.1',
  harfbuzz: '36cb489cb02ce4b92099669ba9f9bea348eff93f',
  override: '#undef HB_NO_LEGACY'
};

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, '..');
const require = createRequire(import.meta.url);

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const [jsDir, hbDir] = process.argv.slice(2);
  if (!jsDir || !hbDir) {
    console.error('usage: node scripts/rebuild-harfbuzz.js <harfbuzzjs-1.6.1 checkout> <harfbuzz checkout at the pinned commit>');
    process.exit(1);
  }
  const work = fs.mkdtempSync(path.join(os.tmpdir(), 'caster-hb-'));
  let bundleDir;
  try {
    fs.cpSync(jsDir, work, { recursive: true, filter: (p) => !p.split(path.sep).includes('.git') && path.relative(jsDir, p) !== 'harfbuzz' });
    fs.cpSync(path.join(hbDir, 'src'), path.join(work, 'harfbuzz', 'src'), { recursive: true });
    fs.appendFileSync(path.join(work, 'config-override.h'), BUILD.override + '\n');
    execFileSync('docker', ['run', '--rm', '-v', `${work}:/src`, '-w', '/src', `emscripten/emsdk@${BUILD.digest}`, 'make', 'harfbuzz'], { stdio: 'inherit' });
    const { build } = await import(require.resolve('esbuild'));
    // harfbuzzjs's own TypeScript API, from the installed package; only the glue and the wasm are replaced.
    const stub = path.join(here, 'vendor-stubs', 'node-absent.js');
    const pkgSrc = fs.realpathSync(path.join(root, 'node_modules', 'harfbuzzjs'));
    bundleDir = fs.mkdtempSync(path.join(os.tmpdir(), 'caster-hb-bundle-'));
    const pkg = path.join(bundleDir, 'node_modules', 'harfbuzzjs');
    fs.mkdirSync(path.join(pkg, 'dist'), { recursive: true });
    fs.copyFileSync(path.join(pkgSrc, 'package.json'), path.join(pkg, 'package.json'));
    fs.copyFileSync(path.join(pkgSrc, 'dist', 'index.mjs'), path.join(pkg, 'dist', 'index.mjs'));
    fs.copyFileSync(path.join(work, 'dist', 'harfbuzz.js'), path.join(pkg, 'dist', 'harfbuzz.js'));
    const result = await build({
      stdin: { contents: 'export * from "harfbuzzjs";', resolveDir: bundleDir },
      bundle: true, format: 'esm', platform: 'browser', target: 'es2022', minify: true, write: false, legalComments: 'none',
      // Emscripten 4 names the node builtins bare, 6 with the `node:` prefix; both sit in a branch a tab never enters.
      alias: { module: stub, fs: stub, path: stub, 'node:module': stub, 'node:fs': stub, 'node:path': stub, 'node:url': stub }
    });
    const text = `/* harfbuzzjs ${BUILD.harfbuzzjs} — one browser ESM module. GENERATED by scripts/rebuild-harfbuzz.js; do not edit. Regenerate: node scripts/rebuild-harfbuzz.js */\n` + result.outputFiles[0].text;
    fs.writeFileSync(path.join(root, 'vendor', 'harfbuzz.js'), text);
    fs.copyFileSync(path.join(work, 'dist', 'harfbuzz.wasm'), path.join(root, 'vendor', 'harfbuzz.wasm'));
    console.log(`vendor/harfbuzz.js: ${Buffer.byteLength(text)} bytes; vendor/harfbuzz.wasm: ${fs.statSync(path.join(root, 'vendor', 'harfbuzz.wasm')).size} bytes`);
  } finally {
    fs.rmSync(work, { recursive: true, force: true });
    if (bundleDir) fs.rmSync(bundleDir, { recursive: true, force: true });
  }
}
