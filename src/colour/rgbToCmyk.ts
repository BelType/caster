/**
 * `colour/rgbToCmyk.js` — the RGB→CMYK conversion tier: a table resolved before emission, by an endpoint or by lcms-wasm.
 *
 * Ported from `harness/src/export/rgbToCmyk.ts` in the `browser-to-pdf-experiments` repository (E12E). Guide: `docs/guide/colour.md` §"The conversion tier (E12E)".
 *
 * WHAT THE PORT CHANGED (PLAN.md §10.2, P5). `convertRgb: 'endpoint'` refuses at the options layer, because BelType serves no colour endpoint. `endpointConversion` and `mockConvertColors` are ported anyway and are exactly what a host that grows one would call; nothing in the pipeline reaches them, and the pure suite is what keeps them honest. `UnknownColorError` is a `CasterError`.
 *
 * `convertRgb: 'wasm'` is built (2026-11-04, `.claude/plans/image-handling/`): {@link textWorklist} reads the work list off the measured runs, {@link lcmsTransform} is the transform over the vendored lcms-wasm, and `print()` gives each converted run's `colorHint` the CMYK before the list is built, so the list carries the result as a text item's `ink` and no writer reads the flag. The transform reads sRGB 8-bit and writes CMYK 16-bit, rounded to the four decimals a content stream writes, so that no downstream writer rounds a tie of its own.
 *
 * The harness's own header follows.
 *
 * E12E (`colour.md`): the RGB→CMYK conversion tier that E8 (`colour.md`) parked.
 *
 * The decision of E8 (`colour.md`) is that the exporter carries no colour management module at all: a declared ink is written as `k` or as a `/Separation`, and every other colour stays `rg` under a per-page `/DefaultRGB` and a document `/OutputIntents`, which is everything a RIP needs to convert it *itself*. That is the right default and it stays the default. What E12E (`colour.md`) adds is the tier above it, for the case E8 named: a print buyer who wants the file to carry the exact ink, converted once, under a stated intent, rather than converted by whichever RIP opens it.
 *
 * Two implementations, and the option that chooses between them:
 *
 * - **`endpoint`**, the preferred one. The exporter posts the unique unhinted RGB colours and the output condition identifier to the gateway; the gateway answers with CMYK. Nothing about colour management is in the exporter and nothing is downloaded into the page. The harness mocks the endpoint with a lookup table generated by `tools/e12e-cmyk-table.mjs` from the same profile the file embeds, so the mock's numbers are Little-CMS's rather than invented.
 * - **`wasm`**, the fallback. `lcms-wasm` is loaded on demand in the browser and given the same profile bytes E8 (`colour.md`) embeds as the output intent. It costs a download and a compile, both of which are measured, and it answers with no network at all.
 *
 * **The policy, in full.** Conversion applies to a colour the document did not declare an ink for, and to nothing else: a run's fill is converted — and only a run's fill: a background or a border rectangle writes `rg` straight from the vector emitter and never reaches the table; a colour behind a `--pdf-color` hint never is — the author named an ink and the exporter's job is to write that ink, not to re-derive one; a colour the black-text policy already claimed never is, for the same reason — `0 0 0 1 k` is a decision about ink coverage that outranks a profile; and an image never is. An image is `/ICCBased` sample data under the output intent, and converting it would mean resampling every pixel through a transform this tier has no business applying — E7 (`images.md`) decided images carry their own colour and E12E (`colour.md`) does not touch that.
 *
 * Everything here is pure: a converter is a *table*, resolved before emission, because the emitter is synchronous and both routes are not. The colours to resolve come from the work list of E8 (`colour.md`), which is the list of colours that stayed `rg` — so the input to E12E (`colour.md`) is literally E8's recorded output.
 *
 * @packageDocumentation
 */
import { CasterError } from '../errors.ts';

import type { Cmyk } from './colorHints.ts';
import type { ReportWorklistEntry, ReportConversionEntry, ReportConversion } from '../report.ts';
import type { MeasuredRun } from '../measure/textMeasure.ts';

/** The exporter option. `none` is the default and is E8 (`colour.md`) unchanged. */
export type ConvertRgbMode = 'none' | 'endpoint' | 'wasm';

/** The rendering intent both routes are specified to use. */
export const INTENT = 'relative colorimetric';

/** Whether black point compensation is on, which it is, for both. */
export const BLACK_POINT_COMPENSATION = true;

/** A colour as the key both routes agree on: the three 0–255 channels. */
export function rgbKey(rgb: readonly number[]): string {
  return rgb.map((channel) => Math.round(channel * 255)).join(',');
}

/** The 0–255 triple of a colour the emitter carries as three fractions. */
export function rgb255(rgb: readonly number[]): [number,number,number] {
  return [Math.round(rgb[0] * 255), Math.round(rgb[1] * 255), Math.round(rgb[2] * 255)];
}

/** One resolved conversion table, and everything the record says about it. */
export type Conversion = {
  mode: 'endpoint' | 'wasm';
  /** The CMYK for one RGB colour, or undefined when the route had no answer. */
  cmykOf: (rgb: readonly number[]) => Cmyk | undefined;
  entries: ReportConversionEntry[];
  wasm?: { package: string, version: string, wasmBytes: number, loadMs: number, transformMs: number };
  endpoint?: { table: string, entries: number, roundTripMs: number };
};

/**
 * The committed lookup table, as the tool script writes it.
 *
 * @remarks
 * It is the mocked endpoint's whole database: a real endpoint would run the same transform on demand, and the difference between the two is a network hop rather than a number.
 */
export type CmykTable = {
  generatedBy: string;
  library: string;
  sourceProfile: { file: string, bytes: number, sha256: string, description: string };
  outputProfile: { file: string, bytes: number, sha256: string, description: string };
  intent: string;
  blackPointCompensation: boolean;
  precision: string;
  entries: { rgb: [number, number, number], key: string, cmyk: Cmyk, from: string }[];
};

/** The error a colour the mocked endpoint was never given produces. */
export class UnknownColorError extends CasterError {
  declare rgb: [number, number, number];
  /**
   * @param rgb - The 0–255 triple that was asked for.
   * @param table - The table that did not hold it.
   */
  constructor(rgb: [number,number,number], table: CmykTable) {
    super(
      `rgbToCmyk: the mocked endpoint has no entry for rgb(${rgb.join(' ')}); ` +
        `${table.generatedBy} lists ${table.entries.length} colour(s) and the fixture asked for one of them to be converted that is not there`,
    );
    this.name = 'UnknownColorError';
    this.rgb = rgb;
  }
}

/**
 * The gateway's colour endpoint, as the harness mocks it.
 *
 * @remarks
 * The signature is the one the `Gateway` interface declares, so an exporter cannot tell this apart from a real endpoint: a list of colours and an output condition go in, a list of CMYK quadruples comes back, and a colour the endpoint cannot answer for is an error rather than a guess.
 *
 * @returns The endpoint; its promise rejects with an {@link UnknownColorError} for a colour the table does not hold.
 */
export function mockConvertColors(table: CmykTable): (colors: readonly [number,number,number][],outputCondition: string) => Promise<Cmyk[]> {
  const byKey = new Map(table.entries.map((entry) => [entry.key, entry.cmyk]));
  return async (colors, outputCondition) => {
    void outputCondition;
    return colors.map((rgb) => {
      const hit = byKey.get(rgb.join(','));
      if (!hit) throw new UnknownColorError(rgb, table);
      return hit;
    });
  };
}

/**
 * Resolve the work list through the gateway endpoint.
 *
 * @remarks
 * One round trip for the whole list rather than one per colour, which is what the endpoint is specified for: a document with two hundred distinct greys is one request, and the round-trip cost is measured once.
 *
 * @param tableName - What the record names the endpoint's table as.
 * @throws {CasterError} An endpoint that answers a different number of colours than it was asked for.
 */
export async function endpointConversion(worklist: readonly ReportWorklistEntry[], outputCondition: string, convertColors: (colors: readonly [number,number,number][],outputCondition: string) => Promise<Cmyk[]>, tableName: string): Promise<Conversion> {
  const colors = worklist.map((entry) => rgb255(entry.rgb));
  const started = now();
  const answers = await convertColors(colors, outputCondition);
  const roundTripMs = now() - started;
  if (answers.length !== colors.length) {
    throw new CasterError(`rgbToCmyk: the endpoint answered ${answers.length} colour(s) for ${colors.length}`);
  }
  const byKey: Map<string,Cmyk> = new Map<any, any>();
  const entries = worklist.map((entry, index) => {
    byKey.set(rgbKey(entry.rgb), answers[index]);
    return { path: entry.path, target: entry.target, rgb: entry.rgb, css: entry.css, cmyk: answers[index], uses: entry.uses };
  });
  return {
    mode: 'endpoint',
    cmykOf: (rgb) => byKey.get(rgbKey(rgb)),
    entries,
    endpoint: { table: tableName, entries: entries.length, roundTripMs: Math.round(roundTripMs * 100) / 100 },
  };
}

/** What the browser side has to supply for the wasm route; see the registry's `lcms` capability. */
export type WasmTransform = {
  /** Convert 0–255 triples to CMYK fractions, all at once. */
  convert: (colors: readonly [number, number, number][]) => Cmyk[];
  /** Bytes of the `.wasm` binary as the browser fetched it. */
  wasmBytes: number;
  /** ms from the first `import()` to a usable transform. */
  loadMs: number;
  packageName: string;
  version: string;
};

/** Resolve the same work list through the in-browser transform. */
export function wasmConversion(worklist: readonly ReportWorklistEntry[], transform: WasmTransform): Conversion {
  const colors = worklist.map((entry) => rgb255(entry.rgb));
  const started = now();
  const answers = transform.convert(colors);
  const transformMs = now() - started;
  const byKey: Map<string,Cmyk> = new Map<any, any>();
  const entries = worklist.map((entry, index) => {
    byKey.set(rgbKey(entry.rgb), answers[index]);
    return { path: entry.path, target: entry.target, rgb: entry.rgb, css: entry.css, cmyk: answers[index], uses: entry.uses };
  });
  return {
    mode: 'wasm',
    cmykOf: (rgb) => byKey.get(rgbKey(rgb)),
    entries,
    wasm: {
      package: transform.packageName,
      version: transform.version,
      wasmBytes: transform.wasmBytes,
      loadMs: Math.round(transform.loadMs * 100) / 100,
      transformMs: Math.round(transformMs * 100) / 100,
    },
  };
}

/** The two routes' answers for the same colour, and how far apart they are. */
export function compareRoutes(endpoint: Conversion, wasm: Conversion): ReportConversionEntry[] {
  return endpoint.entries.map((entry) => {
    const other = wasm.cmykOf(entry.rgb);
    if (!other) return entry;
    const maxDelta = Math.max(...entry.cmyk.map((channel, index) => Math.abs(channel - other[index])));
    return { ...entry, otherCmyk: other, maxDelta: Math.round(maxDelta * 1e6) / 1e6 };
  });
}

/**
 * The whole record, in the shape the report carries.
 *
 * @param condition - The output condition identifier.
 * @param untouched - The colours the policy kept out of the table, and why.
 */
export function conversionRecord(conversion: Conversion, condition: string, entries: ReportConversionEntry[], untouched: { path: string; reason: string; }[], fallbackDecision: string): ReportConversion {
  return {
    mode: conversion.mode,
    condition,
    intent: INTENT,
    blackPointCompensation: BLACK_POINT_COMPENSATION,
    entries,
    untouched,
    ...(conversion.wasm ? { wasm: conversion.wasm } : {}),
    ...(conversion.endpoint ? { endpoint: conversion.endpoint } : {}),
    fallbackDecision,
  };
}

/** A millisecond clock, `performance.now()` where the realm has one. */
function now(): number {
  return typeof performance === 'object' ? performance.now() : Date.now();
}

/** The package version the vendored `vendor/lcms.js` was bundled from; a test reads the bundle's first line against it. */
export const LCMS_WASM_VERSION = '1.0.5';

/** The runs the policy converts: those with no declared ink that the black-text policy has not claimed. */
export function convertibleRuns(lines: readonly { runs: MeasuredRun[] }[], blackText: 'none' | '100k'): MeasuredRun[] {
  const out = new Set<MeasuredRun>();
  for (const line of lines) for (const run of line.runs) {
    if (run.colorHint) continue;
    if (blackText === '100k' && run.rgb[0] === 0 && run.rgb[1] === 0 && run.rgb[2] === 0) continue;
    out.add(run);
  }
  return [...out];
}

/**
 * The colours the conversion tier is asked about: the distinct fills of the runs the author declared no ink for and the black-text policy has not claimed.
 *
 * @remarks
 * The work list of E8 (`colour.md`), read off the measurement rather than off the writer, because the conversion has to be known before the list is built; it takes the runs {@link convertibleRuns} chose. A run's fill is the only paint the policy converts. The entry is the first run's, counted once per run.
 */
export function textWorklist(runs: readonly MeasuredRun[]): ReportWorklistEntry[] {
  const byKey = new Map<string, ReportWorklistEntry>();
  for (const run of runs) {
    const key = rgbKey(run.rgb);
    const held = byKey.get(key);
    if (held) held.uses += 1;
    else byKey.set(key, { path: run.segments[0].blockPath, target: 'fill', rgb: [...run.rgb], css: run.color, uses: 1 });
  }
  return [...byKey.values()];
}

/**
 * The transform over lcms-wasm: Caster's sRGB profile to its CMYK profile, relative colorimetric with black-point compensation.
 *
 * @remarks
 * The transform is built unoptimised (`cmsFLAGS_NOOPTIMIZE`): the default optimisation resamples the profile onto an eight-bit lookup grid and moves a channel by up to 0.0034 from the profile's own arithmetic (measured 2026-11-04 against Little-CMS 2.19's `transicc` on rgb(20 90 200): cyan 0.8665 optimised, 0.8699 by `transicc` and 0.8699 unoptimised), and a work list of a few colours costs nothing to evaluate exactly. `loadMs` is the setup alone (instantiating the module, opening the profiles, building the transform); the caller adds what the capability registry took to import the bundle. The transform is built for one `convert` call, and the instance is the print's own, so nothing is closed.
 *
 * @param lcms - The `lcms` capability.
 * @param srgb - The bytes of `srgb.icc`.
 * @param cmyk - The bytes of `default_cmyk.icc`.
 * @throws {CasterError} A profile lcms refuses to open, or a transform it cannot build.
 */
export async function lcmsTransform(lcms: { module: any, wasm: Uint8Array }, srgb: Uint8Array, cmyk: Uint8Array): Promise<WasmTransform> {
  const started = now();
  const { module } = lcms;
  const instance = await module.instantiate({ wasmBinary: lcms.wasm });
  const from = instance.cmsOpenProfileFromMem(srgb, srgb.byteLength);
  const to = instance.cmsOpenProfileFromMem(cmyk, cmyk.byteLength);
  if (!from || !to) throw new CasterError(`rgbToCmyk: lcms-wasm could not open the ${from ? 'CMYK' : 'sRGB'} profile`);
  const transform = instance.cmsCreateTransform(from, module.TYPE_RGB_8, to, module.TYPE_CMYK_16, module.INTENT_RELATIVE_COLORIMETRIC, module.cmsFLAGS_BLACKPOINTCOMPENSATION | module.cmsFLAGS_NOOPTIMIZE);
  if (!transform) throw new CasterError('rgbToCmyk: lcms-wasm could not build the sRGB to CMYK transform');
  return {
    convert: (colors) => {
      const out: Uint16Array = instance.cmsDoTransform(transform, Uint8Array.from(colors.flat()), colors.length);
      return colors.map((_, i) => [0, 1, 2, 3].map((c) => Math.round(out[i * 4 + c] / 65535 * 1e4) / 1e4) as Cmyk);
    },
    wasmBytes: lcms.wasm.byteLength,
    loadMs: now() - started,
    packageName: 'lcms-wasm',
    version: LCMS_WASM_VERSION,
  };
}
